/* Packs the car glb models into js/*.js as base64 so the game can parse them
   without any network access (file:// , double-click index.html).

   Usage: node tools/embed-car-model.cjs */

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');

const MODELS = [
  {
    key: 'ferrari',
    glb: 'ferrari.glb',
    out: 'car-model.js',
    note: 'three.js webgl_materials_car model, interiors stripped, welded, simplified and quantized'
  },
  {
    key: 'lambo',
    glb: 'lambo-revuelto.glb',
    out: 'car-model-lambo.js',
    note: 'Lamborghini Revuelto, interior removed, batched by material, webp textures, simplified and quantized'
  },
  {
    key: 'temerario',
    glb: 'temerario.glb',
    out: 'car-model-temerario.js',
    note: 'Lamborghini Temerario, built by tools/_gt/build-temerario.mjs: interior removed, +Z rotation baked, body+4 wheel groups, merged by material, simplified, quantized, 512px webp textures'
  },
  {
    key: 'gtr',
    glb: 'gtr.glb',
    out: 'car-model-gtr.js',
    note: 'Nissan GT-R 35 Nismo, built by tools/_gt/build-cars.mjs: 2.07M tris decimated to ~134k, body+4 wheel groups, quantized, 512px webp textures'
  },
  {
    key: 'r8',
    glb: 'r8.glb',
    out: 'car-model-r8.js',
    note: 'Audi R8, converted from r8.obj by obj2gltf then built with tools/build-cars.mjs: 167 groups merged to 26, mm units scaled to metres'
  },
  {
    key: 'mclaren',
    glb: 'mclaren.glb',
    out: 'car-model-mclaren.js',
    note: 'McLaren MP4-5, axle-wide wheel nodes split into left/right, decimated to 145k, 512px webp textures'
  },
  {
    key: 'veyron',
    glb: 'veyron.glb',
    out: 'car-model-veyron.js',
    note: 'Bugatti Veyron, single merged mesh decimated to 30k (wheels cannot be rigged - no separate nodes)'
  },
  {
    key: 'f12',
    glb: 'f12.glb',
    out: 'car-model-f12.js',
    note: 'Ferrari F12, 3.9M triangle configurator mesh built with tools/build-cars.mjs: interior dropped, triangle soup welded by dropping normals, decimated to 86k, normals recomputed'
  }
];

for (const m of MODELS) {
  const src = path.join(root, 'assets', 'car', m.glb);
  const out = path.join(root, 'js', m.out);
  if (!fs.existsSync(src)) {
    console.error('Missing model: ' + src);
    process.exit(1);
  }
  const glb = fs.readFileSync(src);
  const b64 = glb.toString('base64');
  const js =
    '/* Auto-generated by tools/embed-car-model.cjs. Do not edit by hand.\n' +
    '   Source: assets/car/' + m.glb + ' (' + m.note + '). */\n' +
    'window.NR = window.NR || {};\n' +
    'window.NR.CAR_MODELS = window.NR.CAR_MODELS || {};\n' +
    'window.NR.CAR_MODELS.' + m.key + ' = "' + b64 + '";\n';
  fs.writeFileSync(out, js);
  console.log('Wrote js/' + m.out + ' — ' + (js.length / 1048576).toFixed(2) + ' MB from ' +
    (glb.length / 1048576).toFixed(2) + ' MB of glb');
}
